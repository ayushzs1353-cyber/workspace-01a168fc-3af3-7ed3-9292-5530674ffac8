import { useState } from 'react';
import { Link } from 'react-router-dom';
import Icon from '../../components/Icon.jsx';
import PageHeader from '../../components/ui/PageHeader.jsx';
import Card from '../../components/ui/Card.jsx';
import { Button, EmptyState, PillFilters, DemoNotice } from '../../components/ui/index.js';
import { useApp } from '../../state/store.jsx';
import { notificationsFor, unreadCount } from '../../state/selectors.js';
import { timeAgo, formatDateTime } from '../../data/reference.js';

export default function PatientNotifications() {
  const app = useApp();
  const all = notificationsFor(app, app.currentUser);
  const [filter, setFilter] = useState('all');
  const unread = unreadCount(all);

  const rows = all.filter((n) => (filter === 'unread' ? !n.read : true));

  return (
    <>
      <PageHeader
        title="Notifications"
        description="Status changes, delivery updates and messages from your hospital."
        actions={
          <Button
            variant="secondary"
            icon="check"
            disabled={unread === 0}
            onClick={() => app.markAllNotificationsRead(app.currentUser?.role, app.currentUser?.hospitalId)}
          >
            Mark all as read
          </Button>
        }
      />

      <DemoNotice compact />

      <div className="row-between mt-5 mb-3 wrap gap-3">
        <PillFilters
          value={filter}
          onChange={setFilter}
          options={[
            { value: 'all', label: `All (${all.length})` },
            { value: 'unread', label: `Unread (${unread})` },
          ]}
        />
        <span className="text-xs text-muted">Updates are generated by the demo workflow.</span>
      </div>

      <Card flush>
        {rows.length === 0 ? (
          <EmptyState
            icon="bell"
            title={filter === 'unread' ? 'Nothing unread' : 'No notifications yet'}
            description={
              filter === 'unread'
                ? 'You have read every update. New status changes will appear here.'
                : 'Updates about your blood requests will appear here.'
            }
            action={
              filter === 'unread' ? (
                <Button variant="secondary" onClick={() => setFilter('all')}>
                  View all notifications
                </Button>
              ) : (
                <Link to="/patient/new" className="btn btn--primary">
                  Create a request
                </Link>
              )
            }
          />
        ) : (
          rows.map((n) => (
            <div
              key={n.id}
              className="row gap-3"
              style={{
                padding: '16px 20px',
                borderBottom: '1px solid var(--border)',
                background: n.read ? 'var(--white)' : '#fdfbfc',
              }}
            >
              <span
                className="stat__icon"
                style={{
                  background:
                    n.tone === 'danger'
                      ? 'var(--danger-bg)'
                      : n.tone === 'success'
                        ? 'var(--success-bg)'
                        : n.tone === 'warning'
                          ? 'var(--warning-bg)'
                          : 'var(--info-bg)',
                  color:
                    n.tone === 'danger'
                      ? 'var(--danger)'
                      : n.tone === 'success'
                        ? 'var(--success)'
                        : n.tone === 'warning'
                          ? 'var(--warning)'
                          : 'var(--info)',
                  flexShrink: 0,
                }}
              >
                <Icon
                  name={
                    n.tone === 'danger'
                      ? 'alert-triangle'
                      : n.tone === 'success'
                        ? 'check-circle'
                        : n.tone === 'warning'
                          ? 'clock'
                          : 'info'
                  }
                  className="icon icon--sm"
                />
              </span>
              <div className="grow">
                <div className="row gap-2">
                  {!n.read && <span className="badge__dot" style={{ background: 'var(--red-600)' }} />}
                  <span className="text-sm text-strong">{n.title}</span>
                </div>
                <p className="text-sm text-muted mt-1" style={{ lineHeight: 1.5 }}>
                  {n.body}
                </p>
                <div className="row gap-3 mt-2 wrap">
                  <span className="text-xs text-subtle">{formatDateTime(n.at)} · {timeAgo(n.at)}</span>
                  {n.link && (
                    <Link
                      to={n.link}
                      className="text-xs text-strong"
                      onClick={() => app.markNotificationRead(n.id)}
                    >
                      Open request →
                    </Link>
                  )}
                  {!n.read && (
                    <button
                      type="button"
                      className="text-xs"
                      style={{ border: 0, background: 'none', color: 'var(--text-muted)', padding: 0 }}
                      onClick={() => app.markNotificationRead(n.id)}
                    >
                      Mark as read
                    </button>
                  )}
                </div>
              </div>
            </div>
          ))
        )}
      </Card>
    </>
  );
}
