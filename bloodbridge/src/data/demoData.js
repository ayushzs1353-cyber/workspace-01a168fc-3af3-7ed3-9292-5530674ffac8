const stockProfiles = {
  'bank-city': { base: 9, scarce: ['A-', 'AB-', 'O-'], platelets: 4 },
  'bank-lifeline': { base: 7, scarce: ['B-', 'AB-'], platelets: 3 },
  'bank-aravalli': { base: 6, scarce: ['A-', 'O-', 'AB-'], platelets: 2 },
  'bank-meridian': { base: 5, scarce: ['A-', 'B-', 'AB-', 'AB+', 'O-'], platelets: 2 },
};

export function buildInventory() {
  const rows = [];
  BLOOD_BANKS.forEach((bank, bankIndex) => {
    const profile = stockProfiles[bank.id] || { base: 6, scarce: [], platelets: 3 };
    const rand = mulberry32(1000 + bankIndex * 37);
    BLOOD_GROUPS.forEach((group, gi) => {
      COMPONENTS.forEach((comp, ci) => {
        const isScarce = profile.scarce.includes(group);
        let units;
        if (isScarce) units = Math.floor(rand() * 2); // 0–1
        else if (comp.id === 'platelets') units = Math.floor(rand() * profile.platelets * 2);
        else units = 2 + Math.floor(rand() * profile.base);
        if (group === 'O+' && comp.id === 'prbc') units += 5;
        if (group === 'AB+' && comp.id === 'plasma') units += 3;

        const shelfLife = comp.shelfLife;
        const expiryOffset =
          comp.id === 'platelets'
            ? 1 + Math.floor(rand() * 5)
            : 4 + Math.floor(rand() * Math.min(shelfLife, 40));

        rows.push({
          id: `inv-${bank.id}-${group.replace('+', 'p').replace('-', 'n')}-${comp.id}`,
          bankId: bank.id,
          bloodGroup: group,
          component: comp.id,
          units,
          reserved: units > 2 ? Math.floor(rand() * 2) : 0,
          earliestExpiry: ahead(expiryOffset),
          lastUpdated: iso(Math.floor(rand() * 900) + 20),
          threshold: comp.id === 'platelets' ? 3 : 4,
          batchId: `Batch ${String.fromCharCode(65 + gi)}${ci + 1}-${bankIndex + 1}`,
        });
      });
    });
  });
  return rows;
}

