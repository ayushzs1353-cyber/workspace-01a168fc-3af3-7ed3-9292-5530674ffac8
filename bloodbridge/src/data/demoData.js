  Array.from({ length: count }, (_, i) => {
    const offset = startMinutesAgo - i * stepMinutes;
    return {
      at: iso(offset),
      value: Number((base + Math.sin(i / 2.1) * 0.5 + drift * (i / count)).toFixed(1)),
    };
  });

